"复次，善男子，言常随佛学者：如此娑婆世界毗卢遮那如来，从初发心，精进不退，以不可说不可说身命而为布施。剥皮为纸，析骨为笔，刺血为墨，书写经典，积如须弥。为重法故，不惜身命，何况王位、城邑聚落、宫殿园林一切所有。及余种种难行苦行。乃至树下成大菩提，示种种神通，起种种变化，现种种佛身，处种种众会。以圆满音，如大雷震，随其乐欲，成熟众生。乃至示现入于涅槃。如是一切，我皆随学。如今世尊毗卢遮那，如是尽法界虚空界，十方三世一切佛刹，所有尘中一切如来，皆亦如是，于念念中，我皆随学。如是虚空界尽，众生界尽，众生业尽，众生烦恼尽，我此随学无有穷尽。念念相续，无有间断。身语意业，无有疲厌。"

"复次，善男子，言恒顺众生者：谓尽法界虚空界，十方刹海所有众生，种种差别。所谓卵生、胎生、湿生、化生。或有依于地、水、火、风而生住者。或有依空及诸卉木而生住者。种种生类、种种色身、种种形状、种种相貌、种种寿量、种种族类、种种名号、种种心性、种种知见、种种欲乐、种种意行、种种威仪、种种衣服、种种饮食。处于种种村营聚落、城邑宫殿。乃至一切天龙八部、人非人等。无足、二足、四足、多足。有色、无色、有想、无想、非有想非无想。如是等类，我皆于彼随顺而转。种种承事，种种供养，如敬父母，如奉师长及阿罗汉，乃至如来，等无有异。于诸病苦，为作良医；于失道者，示其正路；于暗夜中，为作光明；于贫穷者，令得伏藏。菩萨如是平等饶益一切众生。何以故？菩萨若能随顺众生，则为随顺供养诸佛；若于众生尊重承事，则为尊重承事如来；若令众生生欢喜者，则令一切如来欢喜。何以故？诸佛如来以大悲心而为体故。因于众生而起大悲，因于大悲生菩提心，因菩提心成等正觉。"

